-- 令牌纪元。每次修改口令时 +1，访问令牌里带着签发那一刻的纪元值。
--
-- 为什么需要它：访问令牌是无状态 JWT，签出去就收不回来。
-- "改密码 = 所有设备下线"如果只吊销刷新令牌，被窃取的访问令牌仍能用满整个 TTL
-- （默认 2 小时）—— 功能看着做了，实际只兑现一半。
--
-- 为什么不用"口令变更时间戳 + 比较 iat"：`iat` 只精确到秒。
-- 同一秒内签发的旧令牌会**躲过**比较 —— 本项目的验收脚本第一版正好撞上这一点
-- （注册与改密落在同一秒，旧令牌照样能用）。若把比较放宽 1 秒去救新令牌，
-- 等于给旧令牌开了同样的口子，这个窗口用时间无法消除。
--
-- 纪元是严格递增的整数，比较是精确的：新令牌带 +1 之后的值，旧令牌带旧值，
-- 一次大小判断即可，没有窗口，也不需要任何时间算术。

ALTER TABLE users ADD COLUMN token_epoch INTEGER NOT NULL DEFAULT 1;
